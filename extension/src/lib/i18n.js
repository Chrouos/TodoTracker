export const MESSAGES = Object.freeze({
  'zh-TW': Object.freeze({ ...ZH_TW, ...OPTIONS_ZH_TW }),
  en: Object.freeze({ ...EN, ...OPTIONS_EN }),
  ja: Object.freeze({ ...JA, ...OPTIONS_JA }),
});

const LOCALE_VALUES = new Set(SUPPORTED_LOCALES);

export function normalizeLanguagePreference(value) {
  return LOCALE_VALUES.has(value) || value === 'auto' ? value : 'auto';
}

export function resolveLocale(preference = 'auto', browserLocale = '') {
  const normalizedPreference = normalizeLanguagePreference(preference);
  if (normalizedPreference !== 'auto') return normalizedPreference;
  const normalizedBrowser = String(browserLocale || '').toLowerCase();
  if (normalizedBrowser.startsWith('zh-hant')
    || normalizedBrowser.startsWith('zh-tw')
    || normalizedBrowser.startsWith('zh-hk')
    || normalizedBrowser.startsWith('zh-mo')) return 'zh-TW';
  if (normalizedBrowser === 'ja' || normalizedBrowser.startsWith('ja-')) return 'ja';
  return 'en';
}

export function getBrowserLocale() {
  if (typeof navigator !== 'undefined') return navigator.language || 'en';
  if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
    return chrome.i18n.getUILanguage();
  }
  return 'en';
}

export function translate(locale, key, variables = {}) {
  const dictionary = MESSAGES[resolveLocale(locale, locale)] || MESSAGES.en;
  const message = dictionary[key];
  if (message === undefined) return `[[${key}]]`;
  return message.replace(/\{([^}]+)\}/g, (token, name) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : token
  ));
}

export function applyTranslations(root, locale) {
  if (!root?.querySelectorAll) return;
  const nodes = [];
  if (root.nodeType === 1 && (root.hasAttribute('data-i18n')
    || root.hasAttribute('data-i18n-title')
    || root.hasAttribute('data-i18n-aria-label')
    || root.hasAttribute('data-i18n-placeholder'))) nodes.push(root);
  nodes.push(...root.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-aria-label], [data-i18n-placeholder]'));
  for (const node of nodes) {
    if (node.dataset.i18n) node.textContent = translate(locale, node.dataset.i18n);
    if (node.dataset.i18nTitle) node.title = translate(locale, node.dataset.i18nTitle);
    if (node.dataset.i18nAriaLabel) node.setAttribute('aria-label', translate(locale, node.dataset.i18nAriaLabel));
    if (node.dataset.i18nPlaceholder) node.placeholder = translate(locale, node.dataset.i18nPlaceholder);
  }
}

const intlLocale = (locale) => ({ 'zh-TW': 'zh-TW', en: 'en-US', ja: 'ja-JP' }[resolveLocale(locale, locale)] || 'en-US');

function displayDateValue(value) {
  if (/^\d{4}-\d{2}-\d{2}$/.test(String(value || ''))) {
    const [year, month, day] = value.split('-').map(Number);
    return new Date(year, month - 1, day);
  }
  return new Date(value);
}

export function formatDisplayDate(value, locale) {
  return new Intl.DateTimeFormat(intlLocale(locale), {
    year: 'numeric', month: 'numeric', day: 'numeric', weekday: 'short',
  }).format(displayDateValue(value));
}

export function formatDisplayTime(value, locale) {
  return new Intl.DateTimeFormat(intlLocale(locale), {
    hour: '2-digit', minute: '2-digit', hour12: false,
  }).format(new Date(value));
}

export function formatDuration(seconds, locale) {
  const totalMinutes = Math.max(0, Math.floor(Number(seconds) / 60));
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  const paddedMinutes = String(minutes).padStart(2, '0');
  const resolved = resolveLocale(locale, locale);
  if (resolved === 'zh-TW') return `${hours} 小時 ${paddedMinutes} 分`;
  if (resolved === 'ja') return `${hours}時間 ${paddedMinutes}分`;
  return `${hours}h ${paddedMinutes}m`;
}
